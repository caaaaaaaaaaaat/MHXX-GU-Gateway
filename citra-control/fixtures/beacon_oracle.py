# Independent oracle for fixtures/beacon_n2.hex: MD5/SHA-1 via Python hashlib, AES-128-CTR via the
# third-party cryptography package. Deliberately NOT the C++ implementation under test.
#
# Citra's encrypted-beacon payload contract (docs/G4-BEACON-LENGTH-FIX-SPEC.md):
#   content = 0x12 + 0x1E * n   (BeaconData 18 B + n * BeaconNodeInfo 30 B)
#   total   = 0x28 * n          (n * sizeof(nwm::NodeInfo) = 40: the wire stride)
#   MD5 covers plain[0x10, content)           (2 + 30n bytes)
#   plain[content, total) is an unverified tail (Citra over-reads it); zero here.
#   Tags: 0x18 payload = min(0xFA, total); 0x19 payload = total - 0xFA when total > 0xFA.
#   The two tag payloads are one AES-CTR stream (counter initialised once).
# All inputs below are synthetic hand-chosen values; no capture/ROM/save data is involved.
#
# fixtures/beacon_n1.hex is a FROZEN legacy artifact (old 0x12 + 0x1E*n model, n = 1,
# cipher 48) kept only as a must-reject counter-example; do not regenerate it here.
import hashlib, os, sys
from cryptography.hazmat.primitives.ciphers import Cipher, algorithms, modes

NODE_COUNT = int(sys.argv[2]) if len(sys.argv) > 2 else 2
assert NODE_COUNT >= 2, "n < 2 is Citra's own inconsistent boundary (spec R7)"

# Synthetic parameters (hand chosen, no capture/ROM/save data involved).
host_mac = bytes.fromhex("020000000001")
wlan_comm_id = 0x11223344
beacon_id = 0x07
network_id = 0xAABBCCDD
attributes = 0x0102
bitmask = 0x0003
seed = 0x0102030405060708
# total_nodes is the game-side connected count; max_nodes / records = NODE_COUNT.
total_nodes = NODE_COUNT

# BeaconDataCryptoCTR = host_mac(6) + wlan_comm_id u32_le + id u8 + pad u8 + network_id u32_le
ctr = host_mac + wlan_comm_id.to_bytes(4, "little") + bytes([beacon_id, 0x00]) + network_id.to_bytes(4, "little")

# The 0x1F NetworkInfo tag bytes: oui_value(3) + oui_type(1) + wlan_comm_id u32_be
# + id + pad + attributes u16_be + network_id u32_be + total_nodes + max_nodes
# + pad2 + reserved[11]
nib = (bytes.fromhex("001f32") + bytes([0x15])
       + wlan_comm_id.to_bytes(4, "big") + bytes([beacon_id, 0x00])
       + attributes.to_bytes(2, "big") + network_id.to_bytes(4, "big")
       + bytes([total_nodes, NODE_COUNT, 0, 0]) + bytes(11))
assert len(nib) == 0x1F

appdata = b""
# BeaconData = md5[0x10] + bitmask u16_be, then NODE_COUNT BeaconNodeInfo(0x1E).
node_body = b""
for i in range(NODE_COUNT):
    node_body += ((seed + i).to_bytes(8, "big")
                  + b"".join((0x41 + k).to_bytes(2, "big") for k in range(10))
                  + (i + 1).to_bytes(2, "big"))
body = bitmask.to_bytes(2, "big") + node_body
content = 0x12 + 0x1E * NODE_COUNT
total = 0x28 * NODE_COUNT
assert len(body) == content - 0x10
md5 = hashlib.md5(body).digest()
plain = md5 + body + bytes(total - content)

enc = Cipher(algorithms.AES(bytes(16)), modes.CTR(ctr)).encryptor()
cipher = enc.update(plain) + enc.finalize()
assert len(cipher) == total

sha_body = nib + bytes(20) + bytes([len(appdata)]) + appdata
sha1 = hashlib.sha1(sha_body).digest()

frame = (900000000).to_bytes(8, "little") + (100).to_bytes(2, "little") + (0x0431).to_bytes(2, "little")
frame += bytes([0x00, 0x08]) + bytes(8)
frame += bytes([0xDD, 0x07]) + bytes.fromhex("001f32") + bytes([0x14]) + bytes.fromhex("0a0000")
frame += bytes([0xDD, 52 + len(appdata)]) + nib + sha1 + bytes([len(appdata)]) + appdata
cut = min(0xFA, total)
frame += bytes([0xDD, 4 + cut]) + bytes.fromhex("001f32") + bytes([0x18]) + cipher[:cut]
if total > cut:
    # Citra stores the second tag length in a u8 and ASSERTs it fits (uds_beacon.cpp:278).
    assert 4 + (total - cut) <= 255, "second tag length does not fit Citra's u8"
    frame += bytes([0xDD, 4 + (total - cut)]) + bytes.fromhex("001f32") + bytes([0x19]) + cipher[cut:]

def hx(b):
    s = b.hex()
    return " ".join(s[i:i+16] for i in range(0, len(s), 16))

out = []
out.append("# Synthetic citra-control beacon fixture (fixtures/beacon_n{}.hex).".format(NODE_COUNT))
out.append("# Generated by fixtures/beacon_oracle.py with an INDEPENDENT oracle:")
out.append("#   MD5/SHA-1  : Python hashlib")
out.append("#   AES-128-CTR: Python cryptography (algorithms.AES + modes.CTR), key = 16 zero bytes")
out.append("# max_nodes = {} records, total_nodes = {}, cipher = 0x28*{} = {}, content = 0x12+0x1E*{} = {}.".format(
    NODE_COUNT, total_nodes, NODE_COUNT, total, NODE_COUNT, content))
out.append("# No real capture, ROM, save file or key material is involved.")
out.append("")
out.append("key = " + "00" * 16)
out.append("ctr = " + hx(ctr))
out.append("nib = " + hx(nib))
out.append("plaintext = " + hx(plain))
out.append("md5 = " + hx(md5))
out.append("sha1 = " + hx(sha1))
out.append("ciphertext = " + hx(cipher))
out.append("frame = " + hx(frame))
open(sys.argv[1], "w", newline="\n").write("\n".join(out) + "\n")
print("nodes", NODE_COUNT, "content", content, "total", total)
print("md5", md5.hex())
print("sha1", sha1.hex())
print("ctr", ctr.hex())
print("cipher", cipher.hex())
print("frame_bytes", len(frame), "frame_sha256", hashlib.sha256(frame).hexdigest())
